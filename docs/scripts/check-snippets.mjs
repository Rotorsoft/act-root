#!/usr/bin/env node
/**
 * Doc-snippet type-checker. Copies every fenced ` ```ts ` / ` ```typescript `
 * block out of `docs/docs/**\/*.{md,mdx}` into the gitignored
 * `docs/.snippets/` and type-checks them against the live `@rotorsoft/act`
 * source through `tsconfig.snippets.json`, so shown code can't drift from
 * the API.
 *
 * A block whose info string carries a skip marker isn't compiled. Use it for
 * fragments (pseudo-code, `...` elisions, "don't do this" examples):
 *
 *     ```ts no-check
 *     // a partial fragment that isn't meant to compile on its own
 *     state({ Foo: ... })
 *     ```
 *
 * Recognised markers (any one, case-insensitive): `no-check`, `nocheck`,
 * `no-typecheck`, `skip-check`.
 *
 * `--check` extracts and type-checks through the TypeScript API;
 * `--self-test` proves a broken snippet fails; `--list` prints the
 * extraction plan without writing anything. Pages under `docs/docs/api/`
 * are typedoc output and are skipped.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as ts from "typescript";

const HERE = dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = resolve(HERE, "..");
const SOURCE_DIR = join(DOCS_ROOT, "docs");
const OUT_DIR = join(DOCS_ROOT, ".snippets");
const SNIPPETS_TSCONFIG = join(DOCS_ROOT, "tsconfig.snippets.json");

const SKIP_MARKERS = ["no-check", "nocheck", "no-typecheck", "skip-check"];
// Generated by typedoc (gitignored); its examples are doc-comment fragments.
const GENERATED_DIR = join(SOURCE_DIR, "api");

/** Recursively collect *.md / *.mdx under a directory. */
async function collect_docs(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (full === GENERATED_DIR) continue;
    if (entry.isDirectory()) files.push(...(await collect_docs(full)));
    else if (/\.mdx?$/.test(entry.name)) files.push(full);
  }
  return files.sort();
}

/**
 * Pull fenced ts blocks out of one markdown file. Returns
 * `{ index, info, code, skipped }` per block in document order.
 */
function extract_blocks(text) {
  const blocks = [];
  // ```<lang><meta>\n<code>\n``` — fence must start a line.
  const fence = /^```(ts|typescript)([^\n]*)\n([\s\S]*?)^```/gm;
  let match;
  let index = 0;
  while ((match = fence.exec(text)) !== null) {
    const info = match[2].trim();
    const code = match[3];
    const skipped = SKIP_MARKERS.some((m) =>
      new RegExp(`(^|\\s)${m}(\\s|$)`, "i").test(info)
    );
    blocks.push({ index: index++, info, code, skipped });
  }
  return blocks;
}

/** Sanitise a doc-relative path into a flat, unique filename stem. */
function stem_for(rel) {
  return rel.replace(/\.mdx?$/, "").replace(/[^a-zA-Z0-9]+/g, "_");
}

async function main() {
  const list_only = process.argv.includes("--list");
  const files = await collect_docs(SOURCE_DIR);

  let extracted = 0;
  let skipped = 0;
  const plan = [];

  if (!list_only) {
    await rm(OUT_DIR, { recursive: true, force: true });
    await mkdir(OUT_DIR, { recursive: true });
    // ESM, as the rest of the repo, so top-level `await` compiles.
    await writeFile(join(OUT_DIR, "package.json"), `{ "type": "module" }\n`);
  }

  for (const file of files) {
    const rel = relative(SOURCE_DIR, file);
    const text = await readFile(file, "utf8");
    const blocks = extract_blocks(text);
    for (const block of blocks) {
      if (block.skipped) {
        skipped++;
        continue;
      }
      const name = `${stem_for(rel)}__${block.index}.ts`;
      plan.push({ rel, index: block.index, name });
      if (!list_only) {
        // The header names the source page; `export {}` keeps each snippet's
        // names in its own module.
        const header = `// source: docs/${rel} (block #${block.index})\n`;
        await writeFile(
          join(OUT_DIR, name),
          `${header}${block.code}\nexport {};\n`
        );
      }
      extracted++;
    }
  }

  const verb = list_only ? "would extract" : "extracted";
  console.log(
    `doc snippets: ${verb} ${extracted}, skipped ${skipped} (markers: ${SKIP_MARKERS.join(", ")})`
  );
  if (list_only)
    for (const p of plan) console.log(`  ${p.name}  <-  docs/${p.rel} #${p.index}`);
}

const run = process.argv.includes("--self-test")
  ? self_test
  : process.argv.includes("--check")
  ? check
  : main;
run().catch((err) => {
  console.error(err);
  process.exit(1);
});

/** Extract snippets and type-check them using the TypeScript API. */
async function check() {
  await main(); // extract snippets first
  const result = run_tsc();
  if (result.stdout) console.log(result.stdout);
  if (result.status !== 0) process.exit(result.status);
}

/**
 * Type-check the extracted snippets using the TypeScript API (no tsc binary).
 * The tsconfig must be parsed: `createProgram` ignores `configFilePath`, so
 * passing it alone type-checks zero files and always passes.
 */
function run_tsc() {
  const config = ts.getParsedCommandLineOfConfigFile(SNIPPETS_TSCONFIG, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => {
      throw new Error(ts.flattenDiagnosticMessageText(d.messageText, "\n"));
    },
  });
  if (config.fileNames.length === 0)
    return { status: 1, stdout: "doc snippets: no files to type-check" };
  const program = ts.createProgram(config.fileNames, config.options);
  const diagnostics = [...config.errors, ...ts.getPreEmitDiagnostics(program)];
  const stdout = ts.formatDiagnostics(diagnostics, {
    getCanonicalFileName: (f) => f,
    getCurrentDirectory: () => DOCS_ROOT,
    getNewLine: () => "\n",
  });
  console.log(`doc snippets: type-checked ${config.fileNames.length} files`);
  return { status: diagnostics.length > 0 ? 1 : 0, stdout };
}

/**
 * Negative test: a broken snippet must fail, or the harness is passing
 * everything (a wrong tsconfig, a swallowed exit code).
 */
async function self_test() {
  await main(); // populate OUT_DIR + package.json the normal way
  const broken = join(OUT_DIR, "__selftest_broken__.ts");
  await writeFile(
    broken,
    [
      "// self-test: this MUST fail to type-check.",
      'import { act } from "@rotorsoft/act";',
      "const n: number = act().thisMethodDoesNotExist();",
      "export { n };",
      "",
    ].join("\n")
  );
  const result = run_tsc();
  await rm(broken, { force: true });
  const caught =
    result.status !== 0 &&
    /__selftest_broken__\.ts.*thisMethodDoesNotExist/.test(result.stdout);
  if (!caught) {
    console.error(
      "self-test FAILED: harness did not reject a deliberately-broken snippet"
    );
    console.error(result.stdout);
    process.exit(1);
  }
  console.log("self-test ok: deliberately-broken snippet was rejected");
}
